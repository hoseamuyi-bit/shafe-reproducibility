"""Apply the fixed ARKitScenes temporal screen to a disjoint official split."""

from concurrent.futures import ThreadPoolExecutor
import csv
from datetime import datetime, timezone
from pathlib import Path
from random import Random
from shutil import disk_usage
import subprocess
from zipfile import ZipFile

import cv2
import numpy as np

import expand_arkitscenes_temporal as screen
from fetch_arkitscenes_frames import BASE


OUT = screen.ROOT / 'arkitscenes_temporal_training'
VALIDATION = screen.OUT
INDEX = screen.ROOT / 'arkitscenes_upsampling_split.csv'
FOLD = 'Training'
DRAW = 180
SCREEN = 56
SEED = 20261123
ORIGINAL_ARCHIVE = screen.FrameArchive


def locked(name, content):
    path = OUT / name
    if not path.exists():
        screen.write(path, dict(content, locked_utc=datetime.now(timezone.utc).isoformat()))
    saved = screen.read(path)
    if any(saved[key] != value for key, value in content.items()):
        raise ValueError(f'Locked study has changed: {path}')
    return path


def sample():
    parent = screen.freeze()
    with INDEX.open(newline='', encoding='utf-8') as stream:
        entries = list(csv.DictReader(stream))
    validation = {row['visit_id'] for row in entries if row['fold'] == 'Validation'}
    eligible = {}
    for row in sorted(entries, key=lambda row: row['video_id']):
        if row['fold'] == FOLD and row['visit_id'] not in validation:
            eligible.setdefault(row['visit_id'], row)
    rows = [eligible[v] for v in Random(SEED).sample(sorted(eligible), DRAW)]
    hashes = dict(parent['hashes'], **{Path(__file__).name: screen.digest(Path(__file__))})
    settings = dict(parent['settings'],
                    scope='Follow-up ARKitScenes split, disjoint visit IDs and frozen eligibility rules.')
    expansion = dict(parent['expansion'], max_visits=SCREEN,
                     visit_order='Randomly sample distinct official Training visits. Take the first '
                                 'video ID for each visit. Rank by total plausible centers summed over '
                                 'short-lag pose-only pairs, then number of eligible pairs, then video ID.')
    design = dict(index_sha256=screen.digest(INDEX), hashes=hashes, settings=settings,
                  expansion=expansion, eligible_visits=len(eligible), seed=SEED, candidates=rows,
                  parent_protocol_sha256=screen.digest(VALIDATION / 'protocol.json'))
    return locked('sampling_protocol.json', design), design


def acquire(row, _previous=None):
    video = row['video_id']
    if row['fold'] != FOLD:
        raise ValueError(f'Unexpected split: {row}')
    site = OUT / f'arkit_{video}'
    site.mkdir(exist_ok=True)
    records = {}
    for name in screen.ASSETS:
        file = site / name
        url = f'{BASE}/raw/{FOLD}/{video}/{name}'
        if not file.exists():
            partial = file.with_suffix(file.suffix + '.part')
            subprocess.run(['curl.exe', '-fLsS', '--retry', '2', '--connect-timeout', '15',
                            '--max-time', '60', '--max-filesize', '4000000',
                            '-o', str(partial), url], check=True)
            partial.replace(file)
        if file.suffix == '.zip':
            with ZipFile(file) as archive:
                if archive.testzip():
                    raise ValueError(f'ZIP CRC failed: {file}')
        records[name] = dict(url=url, bytes=file.stat().st_size, sha256=screen.digest(file))
        expected = row.get('assets', {}).get(name)
        if expected and records[name] != expected:
            raise ValueError(f'Frozen geometry asset changed: {file}')
    return site, dict(video_id=video, visit_id=row['visit_id'], fold=FOLD, assets=records)


def priority(row):
    file = OUT / 'pose_priority' / (row['video_id'] + '.json')
    if file.exists():
        return screen.read(file)
    site, result = acquire(row)
    low, wide = (screen.intrinsics(site, label) for label in ('lowres_wide', 'wide'))
    trajectory = np.loadtxt(site / 'lowres_wide.traj')
    lower, upper = trajectory[[0, -1], 0]
    observations = sorted(t for t in wide if lower <= t <= upper)
    if set(observations) & low.keys():
        poses = screen.prepare_poses(trajectory, observations)
        pairs = screen.plan_pairs(low, wide, poses, np.array(observations))
    else:
        pairs = []
    result.update(priority_pairs=len(pairs), priority_centers=sum(p['plausible_centers'] for p in pairs))
    screen.write(file, result)
    return result


def train_archive(site, split, asset):
    if split != 'Validation' or site.parent != OUT:
        raise ValueError('Unexpected frame archive in the locked screening implementation')
    return ORIGINAL_ARCHIVE(site, FOLD, asset)


def keep_scored_frames(row):
    """Discard only downloaded members generated by this run outside the selected case."""
    site = OUT / f'arkit_{row["video"]}'
    chosen = row['selected']
    keep = set()
    if chosen:
        times = (chosen['candidate']['anchor_time'], chosen['candidate']['shifted_time'])
        pair = next(p for p in row['candidates'] if (p['anchor_time'], p['shifted_time']) == times)
        records = dict(highres_depth=pair['depth_source']['frames'],
                       wide=pair['rgb_source']['wide']['frames'],
                       lowres_wide=pair['rgb_source']['low']['frames'])
        keep = {site / asset / Path(frame['member']).name for asset, frames in records.items()
                for frame in frames}
    for asset in ('wide', 'highres_depth', 'lowres_wide'):
        folder = site / asset
        if not folder.exists():
            continue
        parent = folder.resolve()
        if not parent.is_relative_to(OUT.resolve()):
            raise ValueError(f'Unexpected frame directory: {parent}')
        for file in folder.glob('*.png'):
            if file not in keep and file.resolve().parent == parent:
                file.unlink()


def run_screen(row, protocol_sha):
    if disk_usage(OUT).free < 1024**3:
        raise RuntimeError('Insufficient space to start another frame download')
    result = screen.run_visit(row, protocol_sha)
    if not result.get('error'):
        keep_scored_frames(result)
    return result


def main():
    cv2.setNumThreads(1)
    for name in ('pose_priority', 'screened', 'visit_plans'):
        (OUT / name).mkdir(parents=True, exist_ok=True)
    sampling, design = sample()
    print(f'Locked {len(design["candidates"])} disjoint Train visits for pose-only priority', flush=True)
    with ThreadPoolExecutor(max_workers=8) as pool:
        ranking = []
        for count, row in enumerate(pool.map(priority, design['candidates']), start=1):
            ranking.append(row)
            if count % 20 == 0:
                print('Geometry assets ranked', count, flush=True)
    ranking.sort(key=lambda row: (-row['priority_centers'], -row['priority_pairs'], row['video_id']))
    ranked = [row for row in ranking if row['priority_pairs']][:SCREEN]
    path = locked('protocol.json', dict(
        {key: design[key] for key in ('index_sha256', 'hashes', 'settings', 'expansion',
                                    'parent_protocol_sha256')},
        sampling_protocol_sha256=screen.digest(sampling), ranking=ranking, candidates=ranked))
    protocol_sha = screen.digest(path)
    print(f'Frozen {len(ranked)} Training visits for FARO and RGB screening', flush=True)
    # Adapt only storage and the official URL split of the locked implementation.
    screen.OUT, screen.FrameArchive, screen.acquire_geometry = OUT, train_archive, acquire
    final = []
    with ThreadPoolExecutor(max_workers=4) as pool:
        for result in pool.map(lambda row: run_screen(row, protocol_sha), ranked):
            final.append(result)
            print(result['video'], 'selected:', bool(result['selected']), result.get('error', ''), flush=True)
    screen.write(OUT / 'inputs.json', dict(protocol_sha256=protocol_sha, visits=final))


if __name__ == '__main__':
    main()
